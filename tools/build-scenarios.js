// Builds site/scenarios.js: a small index of the playground's scenarios (id,
// title, group, level, story) and its illustrative prices, so the first screen
// (the hero's NAT gateway bill, the incident count, the on-call shift) can be
// drawn before playground.js has loaded.
// Run with: node tools/build-scenarios.js   (tests/check_playground.js keeps it in sync)
"use strict";
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const file = path.join(root, "site/scenarios.js");

function render() {
  const src = path.join(root, "site/playground.js");
  delete require.cache[src];
  require(src);
  const sim = (globalThis.window && globalThis.window.AQSim) || globalThis.AQSim;
  const list = sim.SCENARIOS.map((s) => ({ id: s.id, title: s.title, group: s.group, level: s.level, story: s.story }));
  return `// Generated by tools/build-scenarios.js from site/playground.js. Do not edit.
"use strict";
window.TRACK_PRICES = ${JSON.stringify(sim.PRICES)};
window.TRACK_SCENARIOS = ${JSON.stringify(list, null, 1)};
`;
}

if (require.main === module) {
  fs.writeFileSync(file, render());
  console.log(`wrote ${path.relative(root, file)}`);
}
module.exports = { render, file };
